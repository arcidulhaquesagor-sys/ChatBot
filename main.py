"""
main.py — FastAPI server entry point for the AI Chatbot.

Routes:
    GET  /         → Serves the chat UI (static/index.html)
    POST /api/chat → Streams an AI response via Gemini (text/plain)
"""

import os

from dotenv import load_dotenv
from fastapi import FastAPI
from fastapi.responses import HTMLResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field
import uvicorn

import agent

# Load environment variables from .env (local dev only; Render injects them directly)
load_dotenv()

app = FastAPI(
    title="AI Chatbot",
    description="Streaming chatbot powered by Google Gemini via FastAPI.",
    version="1.0.0",
)

# Serve static assets under /static
app.mount("/static", StaticFiles(directory="static"), name="static")


class ChatRequest(BaseModel):
    """Request body for the /api/chat endpoint."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description="The user's message to send to the AI.",
    )


@app.get("/", response_class=HTMLResponse, include_in_schema=False)
async def serve_ui() -> str:
    """Return the chat UI HTML page."""
    with open("static/index.html", "r", encoding="utf-8") as f:
        return f.read()


@app.post(
    "/api/chat",
    summary="Stream an AI response",
    response_description="Plain-text stream of the AI's reply",
)
async def chat_stream(request: ChatRequest) -> StreamingResponse:
    """
    Accept a user message and return a streaming plain-text response
    generated by the Gemini model.
    """
    return StreamingResponse(
        agent.stream_response(request.message),
        media_type="text/plain",
    )


if __name__ == "__main__":
    port = int(os.getenv("PORT", 8000))
    uvicorn.run("main:app", host="0.0.0.0", port=port, reload=True)
